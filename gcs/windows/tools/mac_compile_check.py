"""Compile-check the Windows GCS app's C# on a Mac or Linux.

The real app (WinUI 3) only builds on Windows: its XAML compiler is a Windows
program. This script compiles every .cs file of the app against the same
packages, with two small stubs standing in for what App.xaml and
MainWindow.xaml generate (InitializeComponent and the Root grid). It catches
C# errors early; it does NOT replace the Windows build in CI, and nothing it
produces can run.

    python3 gcs/windows/tools/mac_compile_check.py     # needs the .NET 10 SDK

The project is generated from BumblebeeGcs.csproj on every run (package
versions and language settings are copied), so it cannot drift from it. Output
goes to gcs/windows/obj/mac-compile-check (git-ignored).
"""
import os
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr

HERE = os.path.dirname(os.path.abspath(__file__))
WIN = os.path.abspath(os.path.join(HERE, '..'))
APP = os.path.join(WIN, 'src', 'BumblebeeGcs')
REAL = os.path.join(APP, 'BumblebeeGcs.csproj')
OUT = os.path.join(WIN, 'obj', 'mac-compile-check')

COPY_PROPERTIES = ('TargetFramework', 'TargetPlatformMinVersion', 'SupportedOSPlatformVersion',
                   'RootNamespace', 'Nullable', 'ImplicitUsings', 'LangVersion')

# What the XAML compiler would generate from App.xaml and MainWindow.xaml.
STUBS = '''// Generated by mac_compile_check.py: stand-ins for XAML-generated code.
namespace BumblebeeGcs
{
    public partial class App
    {
        private void InitializeComponent() { }
    }

    public sealed partial class MainWindow
    {
        private Microsoft.UI.Xaml.Controls.Grid Root = null!;
        private void InitializeComponent() { }
    }
}
'''

EXPECTED_XAML = {'App.xaml', 'MainWindow.xaml'}
WINDOWS_ONLY_TARGETS = {'Microsoft.WindowsAppSDK', 'Microsoft.Windows.SDK.BuildTools'}


def find_dotnet():
    for cand in (os.environ.get('DOTNET'), shutil.which('dotnet'),
                 os.path.expanduser('~/.dotnet/dotnet')):
        if cand and os.path.isfile(cand) and os.access(cand, os.X_OK):
            return cand
    return None


def project_xml():
    root = ET.parse(REAL).getroot()
    props = {}
    for el in root.iter():
        if el.tag in COPY_PROPERTIES and el.text and el.tag not in props:
            props[el.tag] = el.text.strip()
    packages = [(p.get('Include'), p.get('Version')) for p in root.iter('PackageReference')]
    lines = ['<Project Sdk="Microsoft.NET.Sdk">', '  <PropertyGroup>',
             '    <OutputType>Library</OutputType>',
             '    <EnableWindowsTargeting>true</EnableWindowsTargeting>',
             '    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>',
             '    <UseWinUI>false</UseWinUI>',
             '    <Platforms>x64</Platforms>', '    <Platform>x64</Platform>']
    lines += ['    <%s>%s</%s>' % (k, v, k) for k, v in props.items()]
    lines += ['  </PropertyGroup>', '  <ItemGroup>']
    for n, v in packages:
        # Their MSBuild targets run Windows-only tools (XAML compiler, MakePri,
        # Appx tasks); the reference assemblies are all a compile check needs.
        extra = ' ExcludeAssets="build;buildTransitive"' if n in WINDOWS_ONLY_TARGETS else ''
        lines.append('    <PackageReference Include=%s Version=%s%s />' % (quoteattr(n), quoteattr(v), extra))
    lines += ['  </ItemGroup>', '  <ItemGroup>',
              '    <Compile Include=%s Exclude=%s />' % (
                  quoteattr(os.path.join(APP, '**', '*.cs')),
                  quoteattr(os.path.join(APP, 'obj', '**') + ';' + os.path.join(APP, 'bin', '**'))),
              '    <Compile Include="XamlStubs.cs" />',
              '  </ItemGroup>', '</Project>', '']
    return '\n'.join(lines)


def main():
    xaml = {f for f in os.listdir(APP) if f.endswith('.xaml')}
    if xaml != EXPECTED_XAML:
        print('mac_compile_check: XAML files changed (%s); update STUBS for them' % sorted(xaml ^ EXPECTED_XAML),
              file=sys.stderr)
        return 2
    dotnet = find_dotnet()
    if not dotnet:
        print('mac_compile_check: .NET SDK not found (set DOTNET or install it to ~/.dotnet)', file=sys.stderr)
        return 2
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, 'MacCompileCheck.csproj'), 'w', encoding='utf-8') as f:
        f.write(project_xml())
    with open(os.path.join(OUT, 'XamlStubs.cs'), 'w', encoding='utf-8') as f:
        f.write(STUBS)
    env = dict(os.environ, DOTNET_CLI_TELEMETRY_OPTOUT='1', DOTNET_NOLOGO='1')
    env.setdefault('DOTNET_ROOT', os.path.dirname(dotnet))
    cmd = [dotnet, 'build', os.path.join(OUT, 'MacCompileCheck.csproj'), '-c', 'Release',
           '-nologo', '-clp:ErrorsOnly;Summary']
    return subprocess.call(cmd, env=env)


if __name__ == '__main__':
    sys.exit(main())
